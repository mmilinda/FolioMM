export function getLocalizedProject(project, lang = "fr") {
  if (!project) return project;
  const isEn = String(lang).toLowerCase().startsWith("en");
  if (!isEn) return project;

  return {
    ...project,
    title: project.titleEn || project.title,
    description: project.descriptionEn || project.description,
    problem: project.problemEn || project.problem,
    solution: project.solutionEn || project.solution,
    impact: project.impactEn || project.impact,
    client: project.clientEn || project.client,
    status: project.statusEn || project.status,
    category: project.categoryEn || project.category,
    role: project.roleEn || project.role,
  };
}

